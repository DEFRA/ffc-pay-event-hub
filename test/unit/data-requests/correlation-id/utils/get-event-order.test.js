const {
  PAYMENT_EXTRACTED,
  PAYMENT_ENRICHED,
  PAYMENT_PAUSED_HOLD,
  PAYMENT_PAUSED_CROSS_BORDER,
  PAYMENT_PAUSED_DEBT,
  PAYMENT_DEBT_ATTACHED,
  PAYMENT_PAUSED_LEDGER,
  PAYMENT_LEDGER_ASSIGNED,
  PAYMENT_PAUSED_QUALITY_CHECK,
  PAYMENT_QUALITY_CHECK_FAILED,
  PAYMENT_QUALITY_CHECK_PASSED,
  PAYMENT_RESET,
  PAYMENT_PROCESSED,
  PAYMENT_SUBMITTED,
  PAYMENT_DUPLICATE,
  PAYMENT_PROCESSED_NO_FURTHER_ACTION,
  PAYMENT_ACKNOWLEDGED,
  PAYMENT_SETTLED,
  PAYMENT_SUPPRESSED,
  WARNING_PAYMENT_REJECTED,
  WARNING_PAYMENT_REQUEST_BLOCKED,
  WARNING_PAYMENT_PROCESSING_FAILED,
  WARNING_DUPLICATE_PAYMENT,
  WARNING_PAYMENT_DAX_REJECTED,
  WARNING_PAYMENT_INVALID_BANK,
  WARNING_PAYMENT_SETTLEMENT_UNSETTLED,
  WARNING_BATCH_REJECTED
} = require('../../../../../app/constants/events')

const {
  getEventOrder
} = require('../../../../../app/data-requests/correlation-id/utils/get-event-order')

describe('get event order', () => {
  const events = [
    [PAYMENT_EXTRACTED, 1],
    [PAYMENT_ENRICHED, 2],
    [PAYMENT_PAUSED_HOLD, 3],
    [PAYMENT_PAUSED_CROSS_BORDER, 4],
    [PAYMENT_PAUSED_DEBT, 5],
    [WARNING_PAYMENT_REQUEST_BLOCKED, 6],
    [PAYMENT_DEBT_ATTACHED, 7],
    [PAYMENT_PAUSED_LEDGER, 8],
    [PAYMENT_LEDGER_ASSIGNED, 9],
    [PAYMENT_PAUSED_QUALITY_CHECK, 10],
    [PAYMENT_QUALITY_CHECK_FAILED, 11],
    [PAYMENT_QUALITY_CHECK_PASSED, 12],
    [PAYMENT_RESET, 13],
    [PAYMENT_PROCESSED, 14],
    [WARNING_PAYMENT_PROCESSING_FAILED, 15],
    [PAYMENT_SUBMITTED, 16],
    [WARNING_PAYMENT_INVALID_BANK, 17],
    [PAYMENT_PROCESSED_NO_FURTHER_ACTION, 18],
    [PAYMENT_ACKNOWLEDGED, 19],
    [WARNING_PAYMENT_SETTLEMENT_UNSETTLED, 20],
    [PAYMENT_SETTLED, 21],
    [PAYMENT_SUPPRESSED, 22],
    [PAYMENT_DUPLICATE, 23],
    [WARNING_DUPLICATE_PAYMENT, 24],
    [WARNING_PAYMENT_REJECTED, 25],
    [WARNING_PAYMENT_DAX_REJECTED, 26],
    [WARNING_BATCH_REJECTED, 0]
  ]

  test.each(events)('should return %i for event %s', (event, expectedOrder) => {
    const order = getEventOrder(event)
    expect(order).toBe(expectedOrder)
  })
})
